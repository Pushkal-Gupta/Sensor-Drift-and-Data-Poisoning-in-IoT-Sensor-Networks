"""
E1 -- Expected-response generation.

The fog node does not compare a measurement against its own recent history (that
is what Gen-1 FHAD did, and what D1-D4 disclose).  It compares the measurement
against what the *monitored physical process* says the measurement should have
been.  Any model that produces that expectation qualifies: a first-principles
process model, a digital twin, a state estimator, or a learned physics-constrained
relation.  Two embodiments are provided here.

The second property that matters for the invention is *governed adaptation*: the
model's state is re-anchored only on channels that the fog node currently trusts.
A channel under quarantine contributes nothing to the state update, so a poisoned
stream cannot drag the reference it is being judged against.  This is the twin-
level half of the retraining-inhibition feature (E7); without it, a slow false-
data-injection attack simply becomes the new normal.
"""

from __future__ import annotations

from typing import Dict, Optional

import numpy as np

from .config import PlantParams
from .simulator import magnus_es, magnus_es_deriv
from .types import Frame


def _as_weight(x) -> float:
    """Accept either a boolean trust flag or a numeric weight."""
    if isinstance(x, bool):
        return 1.0 if x else 0.0
    return float(x)


class ProcessModel:
    """Interface for an expected-response generator."""

    channels: tuple

    def predict(self, frame: Frame) -> Dict[str, float]:
        raise NotImplementedError

    def update(self, frame: Frame, trust: Dict[str, bool]) -> None:
        raise NotImplementedError

    @property
    def ready(self) -> bool:
        return True


# --------------------------------------------------------------------------
# Embodiment A: first-principles model of the instrumented vessel
# --------------------------------------------------------------------------
class PhysicsVesselTwin(ProcessModel):
    """Physics-informed twin of the heated sealed vessel.

    Structured as a *dedicated observer scheme*: the expected response of each
    channel is generated by a state estimate that excludes that same channel.
    This is essential, not cosmetic.  A single closed-loop estimator tracks its
    own measurements, so the innovation of a slowly biased channel stays at the
    noise floor and the bias is invisible -- exactly the blind spot a slow
    false-data injection is designed to exploit.  With one estimator per channel,
    anchored on the *other* instruments and on the process dynamics, a bias on a
    channel appears in that channel's residual at full amplitude and grows
    without bound.

        expected(T_in)  from P, RH and the thermal dynamics
        expected(P)     from T_in, RH
        expected(RH)    from T_in, P
        expected(T_amb) from the energy balance: T_in - Q*duty/k

    Parameters are deliberately mismatched from the plant (a real twin is never
    exact), so residuals are non-trivial even in nominal operation.
    """

    channels = ("T_in", "T_amb", "P", "RH")
    #: channels for which a leave-one-out temperature estimator is maintained
    OBSERVERS = ("full", "T_in", "P", "RH")

    def __init__(self, p: Optional[PlantParams] = None, param_error: float = 1.0,
                 gain: float = 0.08, robust_clip: float = 4.0,
                 floor_weight: float = 0.02):
        p = p or PlantParams()
        self.p = p
        self.dt = p.dt
        # identified (imperfect) parameters
        self.C_hat = p.C * (1 + 0.030 * param_error)
        self.k_hat = p.k_loss * (1 - 0.025 * param_error)
        self.Q_hat = p.Q * (1 + 0.010 * param_error)
        self.P_ref_hat = p.P_ref * (1 + 0.0008 * param_error)
        self.T_ref = p.T_ref
        self.e_vap_hat = p.e_vap * (1 + 0.015 * param_error)

        self.gain = gain
        self.robust_clip = robust_clip
        self.floor_weight = floor_weight
        self.weight_slew = 0.03
        self._w: Dict[str, float] = {"T_in": 1.0, "P": 1.0, "RH": 1.0}

        # equivalent 1-sigma of each channel expressed in kelvin of T_in,
        # used to weight the multi-channel state update
        self.sigma_T_equiv = {"T_in": 0.05, "P": 0.075, "RH": 0.16}

        #: one temperature estimator per observer; "full" uses every channel
        self.T_obs_est: Dict[str, float] = {}
        self.amb_level: Optional[float] = None
        self.amb_trend: float = 0.0
        self.u_prev: float = 0.0
        self.duty_ema: Optional[float] = None
        self.duty_span: int = 180
        self._pred_cache: Dict[str, float] = {}
        self._T_pred: Dict[str, float] = {}
        self._n = 0

    @property
    def T_est(self) -> Optional[float]:
        """Best available temperature estimate (all channels)."""
        return self.T_obs_est.get("full")

    # -- physical maps -----------------------------------------------------
    def P_of_T(self, T_c: float) -> float:
        return self.P_ref_hat * (T_c + 273.15) / (self.T_ref + 273.15)

    def T_of_P(self, P: float) -> float:
        return (self.T_ref + 273.15) * P / self.P_ref_hat - 273.15

    def RH_of_T(self, T_c: float) -> float:
        return 100.0 * self.e_vap_hat / magnus_es(T_c)

    def T_of_RH(self, RH: float) -> float:
        RH = max(1e-3, RH)
        es = 100.0 * self.e_vap_hat / RH
        z = np.log(es / 610.94)
        return 243.04 * z / (17.625 - z)

    def dRH_dT(self, T_c: float) -> float:
        return -100.0 * self.e_vap_hat * magnus_es_deriv(T_c) / magnus_es(T_c) ** 2

    def dP_dT(self) -> float:
        return self.P_ref_hat / (self.T_ref + 273.15)

    # -- ProcessModel ------------------------------------------------------
    @property
    def ready(self) -> bool:
        return self._n >= 3

    def predict(self, frame: Frame) -> Dict[str, float]:
        """One-step-ahead expected response for every channel."""
        if not self.T_obs_est:
            t0 = frame.values["T_in"]
            self.T_obs_est = {o: t0 for o in self.OBSERVERS}
            self.amb_level = frame.values["T_amb"]
            self.duty_ema = frame.actuation.get("u_heater", 0.0)

        # Newton heating/cooling, driven by the *commanded* heater state,
        # advanced independently for every observer.
        self._T_pred = {}
        for o, Te in self.T_obs_est.items():
            dT = (self.Q_hat * self.u_prev
                  - self.k_hat * (Te - self.amb_level)) / self.C_hat
            self._T_pred[o] = Te + dT * self.dt

        # each channel is compared against an estimate that excludes it
        self._pred_cache = {
            "T_in": self._T_pred["T_in"],
            "P": self.P_of_T(self._T_pred["P"]),
            "RH": self.RH_of_T(self._T_pred["RH"]),
            # ambient by energy balance -- fully independent of the ambient sensor
            "T_amb": frame.values["T_in"] - self.Q_hat * self.duty_ema / self.k_hat,
        }
        return dict(self._pred_cache)

    def update(self, frame: Frame, trust: Dict[str, float]) -> None:
        """Re-anchor the state on trusted channels.

        `trust` maps each channel to a weight in [0, 1] supplied by the
        adaptation governor.  A quarantined channel contributes nothing; a
        channel merely under watch contributes at reduced weight.  If every
        channel is suspect a small floor weight is retained so that the estimator
        degrades gracefully instead of running open loop -- an unanchored model
        would diverge and manufacture deviations of its own.
        """
        if not self._T_pred:
            self.predict(frame)

        # every channel's temperature-equivalent reading
        implied = {
            "T_in": frame.values["T_in"],
            "P": self.T_of_P(frame.values["P"]),
            "RH": self.T_of_RH(frame.values["RH"]),
        }
        # Trust weights are slewed rather than switched.  A step change in the
        # weighting of one anchor re-partitions the estimator between channels of
        # different noise levels and shows up as a jump in every other channel's
        # residual -- estimator chatter that the trigger then reads as a fault.
        for c in implied:
            target = float(_as_weight(trust.get(c, 1.0)))
            self._w[c] += self.weight_slew * (target - self._w[c])
        weights = dict(self._w)
        if sum(weights.values()) <= 1e-9:
            weights = {c: self.floor_weight for c in implied}

        # ---- one governed update per observer, each excluding its channel --
        for o in self.OBSERVERS:
            T_pred = self._T_pred[o]
            num = den = 0.0
            for c, val in implied.items():
                if c == o:
                    continue                       # leave-one-out
                wq = weights[c]
                if wq <= 0.0:
                    continue
                s = self.sigma_T_equiv[c]
                w = wq / s ** 2
                num += w * self._clip(val - T_pred, s)
                den += w
            if den <= 0.0:
                # every remaining anchor is quarantined: coast on the dynamics
                # with a floor weight rather than diverge
                for c, val in implied.items():
                    if c == o:
                        continue
                    s = self.sigma_T_equiv[c]
                    w = self.floor_weight / s ** 2
                    num += w * self._clip(val - T_pred, s)
                    den += w
            corr = (num / den) if den > 0 else 0.0
            self.T_obs_est[o] = T_pred + self.gain * corr

        # heater duty, used by the energy-balance expectation of the ambient
        a = 2.0 / (self.duty_span + 1.0)
        self.duty_ema = ((1 - a) * self.duty_ema
                         + a * frame.actuation.get("u_heater", 0.0))

        # ---- exogenous ambient: Holt linear, gated by weight ----------------
        # The ambient channel has no physical redundancy, so it is de-weighted
        # rather than cut off: a fully unanchored local-trend model diverges.
        wa = max(_as_weight(trust.get("T_amb", 1.0)), self.floor_weight)
        y = frame.values["T_amb"]
        a, b = 0.06 * wa, 0.004 * wa
        new_level = a * y + (1 - a) * (self.amb_level + self.amb_trend)
        self.amb_trend = 0.999 * (b * (new_level - self.amb_level)
                                  + (1 - b) * self.amb_trend)
        self.amb_level = new_level

        self.u_prev = frame.actuation.get("u_heater", self.u_prev)
        self._n += 1

    def _clip(self, x: float, sigma: float) -> float:
        lim = self.robust_clip * sigma
        return float(np.clip(x, -lim, lim))

    # -- introspection used by the consistency stage -----------------------
    def state_temperature(self) -> float:
        return float(self.T_est if self.T_est is not None else 0.0)


# --------------------------------------------------------------------------
# Ablation control: the Generation-1 notion of "expected value"
# --------------------------------------------------------------------------
class RollingMeanTwin(ProcessModel):
    """Expectation = the channel's own recent mean (Gen-1 rolling-mean detrend).

    Not part of the invention -- it is the control condition for the ablation.
    It has no physical content and no cross-channel redundancy, so a bias that
    grows slower than the window forgets it is invisible, and there is no basis
    at all for saying which channel is at fault.
    """

    def __init__(self, channels, window: int = 90):
        self.channels = tuple(channels)
        self.window = window
        self.buf: Dict[str, list] = {c: [] for c in self.channels}

    @property
    def ready(self) -> bool:
        return all(len(b) >= 3 for b in self.buf.values())

    def predict(self, frame: Frame) -> Dict[str, float]:
        out = {}
        for c in self.channels:
            b = self.buf[c]
            out[c] = float(np.mean(b)) if b else frame.values[c]
        return out

    def update(self, frame: Frame, trust: Dict[str, float]) -> None:
        for c in self.channels:
            self.buf[c].append(frame.values[c])
            if len(self.buf[c]) > self.window:
                self.buf[c].pop(0)


# --------------------------------------------------------------------------
# Embodiment B: single-channel climatological / seasonal process model
# --------------------------------------------------------------------------
class SeasonalHarmonicTwin(ProcessModel):
    """Expected response for a single environmental channel with no redundancy.

    Used for the legacy daily-minimum-temperature record, so the Gen-2 pipeline
    can be run head-to-head against Gen-1 FHAD on the exact dataset of the
    original disclosure.  The "process model" here is a fitted annual harmonic
    climatology plus an AR(1) innovation term -- physics-lite, but still an
    expectation derived from the process rather than from the recent history of
    the signal itself.
    """

    def __init__(self, period: float = 365.25, n_harmonics: int = 3,
                 ar_phi: float = 0.55, channel: str = "value"):
        self.period = period
        self.n_harmonics = n_harmonics
        self.ar_phi = ar_phi
        self.channel = channel
        self.channels = (channel,)
        self.coef: Optional[np.ndarray] = None
        self.prev_resid: float = 0.0
        self._ready = False

    def _design(self, t: np.ndarray) -> np.ndarray:
        cols = [np.ones_like(t)]
        for h in range(1, self.n_harmonics + 1):
            cols.append(np.sin(2 * np.pi * h * t / self.period))
            cols.append(np.cos(2 * np.pi * h * t / self.period))
        return np.column_stack(cols)

    def fit(self, t: np.ndarray, y: np.ndarray) -> "SeasonalHarmonicTwin":
        X = self._design(np.asarray(t, dtype=float))
        self.coef, *_ = np.linalg.lstsq(X, np.asarray(y, dtype=float), rcond=None)
        self._ready = True
        return self

    @property
    def ready(self) -> bool:
        return self._ready

    def predict(self, frame: Frame) -> Dict[str, float]:
        if self.coef is None:
            return {self.channel: frame.values[self.channel]}
        X = self._design(np.array([frame.t], dtype=float))
        base = float(X @ self.coef)
        return {self.channel: base + self.ar_phi * self.prev_resid}

    def update(self, frame: Frame, trust: Dict[str, float]) -> None:
        if _as_weight(trust.get(self.channel, 1.0)) < 0.5:
            self.prev_resid *= self.ar_phi      # coast, do not absorb
            return
        pred = self.predict(frame)[self.channel]
        self.prev_resid = frame.values[self.channel] - pred
